export const normalizeLanguage = language => language === 'en' ? 'en' : 'zh';
export const localeFor = language => normalizeLanguage(language) === 'en' ? 'en-US' : 'zh-CN';
const chinese = { BRANCH: '分支', TASK: '任务', OPERATION: '行动', CHAPTER: '章节', 'DEVELOPMENT / OPERATION MAP': '开发 / 行动地图' };

export function createTranslator(language = 'zh') {
  const en = normalizeLanguage(language) === 'en';
  return (message, values = {}) => (en ? english[message] ?? message : chinese[message] ?? message)
    .replace(/\{(\w+)\}/g, (placeholder, key) => Object.hasOwn(values, key) ? String(values[key]) : placeholder);
}

const canonicalStates = {
  development: { planned: ['未开始', 'Not started'], active: ['进行中', 'In progress'], done: ['已完成', 'Done'], blocked: ['阻塞', 'Blocked'] },
  verification: { passed: ['已通过', 'Passed'], failed: ['未通过', 'Failed'], partial: ['部分通过', 'Partially passed'] },
  acceptance: { pending: ['待验收', 'Awaiting acceptance'], accepted: ['已验收', 'Accepted'], unaccepted: ['未验收', 'Not accepted'] },
  delivery: { undelivered: ['未交付', 'Not delivered'], delivered: ['已交付', 'Delivered'], partial: ['部分交付', 'Partially delivered'] },
};

export function stateLabel(language, field, state, raw) {
  if (normalizeLanguage(language) === 'zh' && raw) return raw;
  const label = canonicalStates[field]?.[state];
  if (label) return label[normalizeLanguage(language) === 'en' ? 1 : 0];
  return raw && raw !== '未记录' ? raw : createTranslator(language)('未记录');
}

// Capture static text once, before live task content enters the document.
export function bindStaticTranslations(document) {
  const bindings = [];
  const walker = document.createTreeWalker(document.body, 4);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.parentElement?.closest('script,style')) continue;
    const message = node.textContent.trim();
    if (Object.hasOwn(english, message)) bindings.push({ node, message, original: node.textContent });
  }
  for (const node of document.querySelectorAll('[title],[aria-label],[placeholder]')) {
    for (const attribute of ['title', 'aria-label', 'placeholder']) {
      const message = node.getAttribute(attribute);
      if (Object.hasOwn(english, message)) bindings.push({ node, message, attribute });
    }
  }
  return language => {
    const t = createTranslator(language);
    document.documentElement.lang = localeFor(language);
    for (const { node, message, attribute, original } of bindings) {
      if (attribute) node.setAttribute(attribute, t(message));
      else node.textContent = original.replace(message, t(message));
    }
  };
}
